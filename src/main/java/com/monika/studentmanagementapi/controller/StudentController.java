package com.monika.studentmanagementapi.controller;

import com.monika.studentmanagementapi.exception.ErrorResponse;
import com.monika.studentmanagementapi.model.Student;
import com.monika.studentmanagementapi.service.StudentService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Positive;
import java.net.URI;
import java.util.List;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/** Handles HTTP requests for /api/students and delegates the work to StudentService. */
@RestController
@RequestMapping("/api/students")
@Validated // enables validation of path variables such as @Positive
@Tag(name = "Students", description = "CRUD operations for student records")
public class StudentController {

    private final StudentService studentService;

    // Constructor injection: Spring supplies the StudentService.
    public StudentController(StudentService studentService) {
        this.studentService = studentService;
    }

    @PostMapping
    @Operation(summary = "Create a student",
            description = "Adds a new student. The id is generated by the server.")
    @ApiResponse(responseCode = "201", description = "Student created",
            content = @Content(schema = @Schema(implementation = Student.class)))
    @ApiResponse(responseCode = "400", description = "Invalid input (blank field, bad email, year outside 1-4, malformed JSON)",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Student> createStudent(@Valid @RequestBody Student student) {
        Student created = studentService.create(student);
        URI location = URI.create("/api/students/" + created.getId());
        return ResponseEntity.created(location).body(created); // 201 + Location header
    }

    @GetMapping
    @Operation(summary = "Get all students",
            description = "Returns every student, ordered by id. Returns an empty list when there are none.")
    @ApiResponse(responseCode = "200", description = "List of students",
            content = @Content(array = @ArraySchema(schema = @Schema(implementation = Student.class))))
    public ResponseEntity<List<Student>> getAllStudents() {
        return ResponseEntity.ok(studentService.findAll());
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get a student by id", description = "Returns one student.")
    @ApiResponse(responseCode = "200", description = "Student found",
            content = @Content(schema = @Schema(implementation = Student.class)))
    @ApiResponse(responseCode = "400", description = "Id is not a positive number",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "No student with this id",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Student> getStudentById(
            @Parameter(description = "Id of the student", example = "1")
            @PathVariable @Positive(message = "id must be a positive number") Long id) {
        return ResponseEntity.ok(studentService.findById(id));
    }

    @PutMapping("/{id}")
    @Operation(summary = "Update a student",
            description = "Replaces all fields of an existing student. The id itself cannot be changed.")
    @ApiResponse(responseCode = "200", description = "Student updated",
            content = @Content(schema = @Schema(implementation = Student.class)))
    @ApiResponse(responseCode = "400", description = "Invalid id or invalid input",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "No student with this id",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Student> updateStudent(
            @Parameter(description = "Id of the student to update", example = "1")
            @PathVariable @Positive(message = "id must be a positive number") Long id,
            @Valid @RequestBody Student student) {
        return ResponseEntity.ok(studentService.update(id, student));
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete a student", description = "Removes a student permanently (until restart, data is in memory anyway).")
    @ApiResponse(responseCode = "204", description = "Student deleted (no response body)")
    @ApiResponse(responseCode = "400", description = "Id is not a positive number",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "No student with this id",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Void> deleteStudent(
            @Parameter(description = "Id of the student to delete", example = "1")
            @PathVariable @Positive(message = "id must be a positive number") Long id) {
        studentService.delete(id);
        return ResponseEntity.noContent().build();
    }
}
